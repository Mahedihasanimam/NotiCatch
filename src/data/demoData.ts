export async function hasDemoData(): Promise<boolean> {
  try {
    const all = await readAllRecords(100);
    return all.some((r) => r.sbnKey.startsWith('demo:'));
  } catch {
    return false;
  }
}

export async function loadDemoData(): Promise<number> {
  await clearDemoData();
  const records = getDemoBackupRecords();
  const res = await importRecords(records);
  return res.inserted;
}

export async function clearDemoData(): Promise<number> {
  try {
    const all = await readAllRecords(500);
    const demoIds = all.filter((r) => r.sbnKey.startsWith('demo:')).map((r) => r.id);
    if (demoIds.length > 0) {
      await deleteNotifications(demoIds);
      return demoIds.length;
    }
    return 0;
  } catch {
    return 0;
  }
}
